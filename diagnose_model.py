def flaw6_real_far_estimate(X_bio):
    sep("FLAW 6  —  What is the TRUE False Acceptance Rate?")
    print(f"\n  We can estimate real FAR using a Leave-One-Out style test:")
    print(f"  Train on N-1 owner sessions, score the Nth as 'intruder'.")
    print(f"  (The model should NOT accept sessions from a true outsider")
    print(f"   but we test how often it accepts its own held-out sessions.)")

    n = len(X_bio)
    inside_scores = []
    for i in range(n):
        X_train = np.delete(X_bio, i, axis=0)
        X_test  = X_bio[[i]]
        sc = StandardScaler()
        X_tr_sc = sc.fit_transform(X_train)
        X_te_sc = sc.transform(X_test)
        model = OneClassSVM(kernel="rbf", nu=0.01, gamma="scale")
        model.fit(X_tr_sc)
        raw = model.decision_function(X_te_sc)
        score = sigmoid(raw)[0]
        inside_scores.append(score)
        label = "ACCEPT" if score < 0.55 else "REJECT own session!"

    accepted = sum(1 for s in inside_scores if s < 0.55)
    rejected = n - accepted
    print(f"\n  Leave-One-Out results across {n} sessions:")
    print(f"    Owner sessions correctly accepted : {accepted}/{n} ({accepted/n*100:.1f}%)")
    print(f"    Owner sessions wrongly rejected   : {rejected}/{n} ({rejected/n*100:.1f}%)")
    print(f"\n  Score distribution of owner's own sessions:")
    arr = np.array(inside_scores)
    print(f"    Mean score  : {arr.mean():.4f}")
    print(f"    Std score   : {arr.std():.4f}")
    print(f"    Min score   : {arr.min():.4f}")
    print(f"    Max score   : {arr.max():.4f}")
    print(f"    % below 0.55 (accepted): {np.sum(arr < 0.55)/len(arr)*100:.1f}%")
    print(f"\n  => True owner acceptance is likely {accepted/n*100:.0f}%, NOT the 88-100% we claimed.")
    print(f"     The reported 'intruder rejection' of 98-100% was on synthetic data")
    print(f"     generated by shifting the SAME owner's mean — an unfair advantage.")

