def flaw5_seed_sensitivity(X_bio):
    sep("FLAW 5  —  Results Are Highly Seed-Sensitive (Overfitting to Evaluation)")
    from itertools import product as iproduct
    import random

    rng_master = np.random.default_rng(99)
    seeds = [0, 7, 13, 42, 99, 123, 256, 512, 1000, 2024]
    results = []

    def make_intruder(X_train_bio, n, low, high, seed):
        rng = np.random.default_rng(seed)
        mu  = X_train_bio.mean(axis=0)
        std_ = X_train_bio.std(axis=0) + 1e-8
        shift = rng.uniform(low, high, size=mu.shape) * rng.choice([-1,1], size=mu.shape)
        center = np.clip(mu + shift * std_, 0, None)
        grp_std = std_ * rng.uniform(0.85, 1.15, size=std_.shape)
        return np.clip(rng.normal(loc=center, scale=grp_std, size=(n, mu.shape[0])), 0, None)

    n = len(X_bio)
    split = int(n * 0.8)
    print(f"\n  Running 10 different random seeds, same nu=0.01, gamma='scale':")
    print(f"\n  {'Seed':>6} {'OwnerAcc%':>11} {'IntruderRej%':>14} {'BalAcc%':>10}")
    print("  " + "-" * 46)

    for seed in seeds:
        rng = np.random.default_rng(seed)
        idx = rng.permutation(n)
        X_tr = X_bio[idx[:split]]
        X_te = X_bio[idx[split:]]

        n_h = int(150 * 0.35); n_m = int(150 * 0.40); n_e = 150 - n_h - n_m
        X_in = np.vstack([
            make_intruder(X_tr, n_h, 0.3, 0.7,  seed),
            make_intruder(X_tr, n_m, 0.7, 1.2,  seed+1),
            make_intruder(X_tr, n_e, 1.2, 1.8,  seed+2),
        ])

        sc = StandardScaler(); X_tr_sc = sc.fit_transform(X_tr)
        X_te_sc = sc.transform(X_te); X_in_sc = sc.transform(X_in)
        model = OneClassSVM(kernel="rbf", nu=0.01, gamma="scale")
        model.fit(X_tr_sc)

        oa_s = sigmoid(model.decision_function(X_te_sc))
        in_s = sigmoid(model.decision_function(X_in_sc))
        y_t = np.concatenate([np.zeros(len(X_te)), np.ones(len(X_in))])
        y_s = np.concatenate([oa_s, in_s])
        y_p = (y_s >= 0.55).astype(int)
        tn,fp,fn,tp = confusion_matrix(y_t, y_p, labels=[0,1]).ravel()
        oa_ = tn/(tn+fp)*100 if (tn+fp)>0 else 0
        ir_ = tp/(tp+fn)*100 if (tp+fn)>0 else 0
        ba_ = balanced_accuracy_score(y_t, y_p)*100
        results.append((oa_, ir_, ba_))
        print(f"  {seed:>6} {oa_:>10.1f}% {ir_:>13.1f}% {ba_:>9.1f}%")

    oa_arr = [r[0] for r in results]
    ir_arr = [r[1] for r in results]
    ba_arr = [r[2] for r in results]
    print(f"\n  {'MEAN':>6} {np.mean(oa_arr):>10.1f}% {np.mean(ir_arr):>13.1f}% {np.mean(ba_arr):>9.1f}%")
    print(f"  {'STD':>6} {np.std(oa_arr):>10.1f}% {np.std(ir_arr):>13.1f}% {np.std(ba_arr):>9.1f}%")
    print(f"  {'MIN':>6} {np.min(oa_arr):>10.1f}% {np.min(ir_arr):>13.1f}% {np.min(ba_arr):>9.1f}%")
    print(f"  {'MAX':>6} {np.max(oa_arr):>10.1f}% {np.max(ir_arr):>13.1f}% {np.max(ba_arr):>9.1f}%")
    print(f"\n  => High std across seeds reveals evaluation INSTABILITY.")
    print(f"     The model is not as consistent as the cherry-picked result implies.")

